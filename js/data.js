// Fonction pour filtrer les mangas par genre
function filtrerParGenre(genre) {
  if (genre === 'Tous') return mangas;
  return mangas.filter(manga => manga.genre.includes(genre));
}

// Fonction pour rechercher des mangas
function rechercherManga(terme) {
  const termeLower = terme.toLowerCase();
  return mangas.filter(manga =>
    manga.titre.toLowerCase().includes(termeLower) ||
    manga.auteur.toLowerCase().includes(termeLower) ||
    manga.genre.some(g => g.toLowerCase().includes(termeLower))
  );
}

// Fonction pour obtenir un manga par ID
function getMangaById(id) {
  return mangas.find(manga => manga.id === parseInt(id));
}


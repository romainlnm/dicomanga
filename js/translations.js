// Fonction pour obtenir le texte traduit d'un manga
function getMangaText(manga, field) {
  const lang = currentLang || 'fr';

  // Si la langue est français, retourner le texte original
  if (lang === 'fr') {
    return manga[field];
  }

  // Sinon, chercher la traduction
  const translation = mangaTranslations[lang]?.[manga.id];
  if (translation && translation[field]) {
    return translation[field];
  }

  // Fallback vers le français
  return manga[field];
}

// Fonction pour obtenir les personnages traduits
function getMangaCharacters(manga) {
  const lang = currentLang || 'fr';

  if (lang === 'fr') {
    return manga.personnages;
  }

  const translation = mangaTranslations[lang]?.[manga.id];
  if (translation && translation.personnages) {
    return translation.personnages;
  }

  return manga.personnages;
}
